"""Generate image6 constants and DDR payload from the frozen QDQ model."""
import argparse
import hashlib
import json
from pathlib import Path
import sys
import zlib


def main():
    p=argparse.ArgumentParser()
    p.add_argument('--model-root',type=Path,default=Path('E:/Efinity_Project/FPGA_GAME'))
    a=p.parse_args();sys.path.insert(0,str(a.model_root))
    from fourpoint.fpga_integer import export,DEFAULT_GRAPH
    import numpy as np
    root=Path(__file__).resolve().parents[1]
    output=root/'tmp/image6_parameters'
    contract=export(DEFAULT_GRAPH,output)
    image=root/'images/image6_pose_int16'
    (image/'model-contract.json').write_text(json.dumps(contract,indent=2)+'\n',encoding='utf-8')
    biases=np.fromfile(output/'biases.bin',dtype='<i4')
    header=['// Generated by tools/export-image6.py; do not hand edit.',
            '// QDQ SHA256: '+contract['graph_sha256'],
            'reg [5:0] ci,co; reg [7:0] ih,oh,ow; reg [8:0] iw;',
            'reg [1:0] stride,kernel; reg [2:0] dilation,pad;',
            'reg [15:0] input_zero,conv_zero,output_zero;',
            'reg use_relu; reg [30:0] post_multiplier; reg [5:0] post_shift;',
            'reg [31:0] source_base,destination_base,weight_base;',
            'always @* begin',
            'ci=1;co=1;ih=1;iw=1;oh=1;ow=1;stride=1;kernel=1;dilation=1;pad=0;',
            'input_zero=0;conv_zero=0;output_zero=0;use_relu=0;post_multiplier=0;post_shift=0;',
            'source_base=0;destination_base=0;weight_base=0;',
            'case(layer)']
    rom=['function [68:0] channel_constants;', 'input [3:0] stage;input [5:0] channel;',
         'begin case({stage,channel})']
    for i,s in enumerate(contract['stages']):
        header.append(f'4\'d{i}:begin // {s["id"]}')
        for k in ['ci','co','ih','iw','oh','ow','stride','kernel','dilation','input_zero','conv_zero','output_zero','post_shift']:
            header.append(f'{k}={s[k]};')
        header.extend([f'pad={s["dilation"] if s["kernel"]==3 else 0};',f'use_relu=1\'b{int(s["relu"])};',
                       f'post_multiplier=31\'d{s["post_mult"]};',f'source_base=32\'h{s["source_address"]:08x};',
                       f'destination_base=32\'h{s["output_address"]:08x};',
                       f'weight_base=32\'h{contract["parameter_base"]+s["packed_weight_offset"]:08x};','end'])
        b=biases[s['bias_offset']//4:s['bias_offset']//4+s['co']]
        for oc in range(s['co']):
            value=(s['shift'][oc]<<63)|(s['mult'][oc]<<32)|(int(b[oc])&0xffffffff)
            rom.append(f'10\'d{i*64+oc}:channel_constants=69\'h{value:018x};')
    header.extend(['endcase','end']);rom.extend(["default:channel_constants=69'd0;",'endcase end endfunction'])
    (image/'pose6_layer_config.vh').write_text('\n'.join(header+rom)+'\n',encoding='utf-8')
    weights=(output/'weights_lanes16.bin').read_bytes()
    # Upload packets use 16-byte aligned lengths and an IEEE CRC32.
    (output/'model.bin').write_bytes(weights+b'\0'*((-len(weights))%16))
    model_crc=zlib.crc32((output/'model.bin').read_bytes())
    (image/'pose6_model_identity.vh').write_text(
        f"localparam POSE6_MODEL_BYTES={len((output/'model.bin').read_bytes())};\n"
        f"localparam [31:0] POSE6_MODEL_CRC=32'h{model_crc:08x};\n",encoding='utf-8')
    report=dict(bytes=len(weights),model_crc32=f'{model_crc:08x}',model_sha256=hashlib.sha256((output/'model.bin').read_bytes()).hexdigest(),
                contract_sha256=hashlib.sha256((image/'model-contract.json').read_bytes()).hexdigest())
    (output/'manifest.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report))


if __name__=='__main__':main()
