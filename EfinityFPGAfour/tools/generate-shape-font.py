"""Generate the six fixed Chinese bitmap glyphs used by image1's labels.

Requires Pillow only when regenerating; FPGA builds use the checked-in RTL.
Noto Sans SC is available under SIL OFL; this output contains rendered glyphs,
not font software. Pixel rows are MSB-left, top-to-bottom, enlarged 2x in RTL.
"""
from pathlib import Path
import argparse
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("--font", default="C:/Windows/Fonts/Noto Sans SC (TrueType).otf")
args = parser.parse_args()
root = Path(__file__).resolve().parents[1]
font = ImageFont.truetype(args.font, 16)
lines = ["`timescale 1ns/1ps", "", "// Generated by tools/generate-shape-font.py from Noto Sans SC, 16px.",
         "// glyph IDs: 0=检, 1=测, 2=到, 3=圆, 4=形, 5=矩. MSB is left.",
         "module shape_chinese_font(input [2:0] glyph, input [3:0] row,",
         "                          output reg [15:0] pixels);",
         "always @* begin", "    case ({glyph,row})"]
for index, char in enumerate("检测到圆形矩"):
    bitmap = Image.new("L", (16, 16))
    ImageDraw.Draw(bitmap).text((0, 0), char, font=font, fill=255, anchor="lt")
    for row in range(16):
        bits = sum((bitmap.getpixel((col, row)) >= 96) << (15-col) for col in range(16))
        lines.append(f"        7'h{index*16+row:02x}: pixels = 16'h{bits:04x};")
lines += ["        default: pixels = 16'h0000;", "    endcase", "end", "endmodule", ""]
(root / "src/vision/shape_chinese_font.v").write_text("\n".join(lines), encoding="utf-8")
print("Generated six 16x16 glyphs: 检测到圆形矩")
